"""Текст, который «генерирует» фейковая модель.

Смысл ответа не важен: важны число токенов и время. Один токен — одно слово,
а длина промпта оценивается по словам — грубо, но предсказуемо.
"""

WORDS = ("альфа", "бета", "гамма", "дельта", "эпсилон", "дзета", "эта", "тета")


def make_tokens(count: int) -> list[str]:
    """Возвращает count токенов; склеенные подряд, они дают текст ответа."""
    return [WORDS[i % len(WORDS)] + (" " if i < count - 1 else "") for i in range(count)]


def count_words(text: str) -> int:
    return len(text.split())
